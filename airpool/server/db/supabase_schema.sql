create table if not exists public.airpool_users (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null unique,
  password_hash text not null,
  domain text not null,
  verified boolean not null default false,
  created_at timestamptz not null default now()
);
create table if not exists public.airpool_auth_otps (
  email text primary key references public.airpool_users(email) on delete cascade,
  otp_hash text not null,
  expires_at timestamptz not null
);
create table if not exists public.airpool_circles (
  id bigint generated by default as identity primary key,
  name text not null,
  domain text not null unique
);
create table if not exists public.airpool_circle_members (
  user_id bigint not null references public.airpool_users(id) on delete cascade,
  circle_id bigint not null references public.airpool_circles(id) on delete cascade,
  verified_at timestamptz not null default now(),
  primary key(user_id,circle_id)
);
create table if not exists public.airpool_emergency_contacts (
  user_id bigint primary key references public.airpool_users(id) on delete cascade,
  contact text not null,
  updated_at timestamptz not null default now()
);
create table if not exists public.airpool_airports (
  id bigint generated by default as identity primary key,
  name text not null,
  code text not null unique,
  lat double precision not null,
  lng double precision not null
);
create table if not exists public.airpool_zones (
  id bigint generated by default as identity primary key,
  name text not null,
  lat double precision not null,
  lng double precision not null,
  airport_code text not null references public.airpool_airports(code),
  corridor text not null default 'city',
  unique(name,airport_code)
);
create table if not exists public.airpool_fare_rates (
  vehicle_type text primary key,
  per_km numeric(10,2) not null check(per_km between 1 and 200),
  minimum_fare numeric(10,2) not null check(minimum_fare >= 0),
  night_surcharge numeric(10,2) not null default 0 check(night_surcharge >= 0),
  updated_at timestamptz not null default now()
);
create table if not exists public.airpool_distance_cache (
  origin text not null,
  destination text not null,
  km numeric(10,3) not null,
  updated_at timestamptz not null default now(),
  primary key(origin,destination)
);
create table if not exists public.airpool_fare_checks (
  id bigint generated by default as identity primary key,
  origin text not null,
  destination text not null,
  vehicle_type text not null,
  distance_km numeric(10,2) not null,
  quoted_fare numeric(10,2),
  estimate_low numeric(10,2) not null,
  estimate_high numeric(10,2) not null,
  verdict text not null,
  created_at timestamptz not null default now()
);
create table if not exists public.airpool_ratings (
  id bigint generated by default as identity primary key,
  request_id bigint,
  stars integer not null check(stars between 1 and 5),
  comment text not null default '',
  created_at timestamptz not null default now()
);
create table if not exists public.airpool_sos_events (
  id bigint generated by default as identity primary key,
  user_id bigint references public.airpool_users(id) on delete set null,
  request_id bigint,
  note text not null default '',
  created_at timestamptz not null default now()
);
create table if not exists public.airpool_contact_messages (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  message text not null,
  created_at timestamptz not null default now()
);
create table if not exists public.airpool_events (
  id bigint generated by default as identity primary key,
  type text not null,
  payload_json jsonb not null,
  created_at timestamptz not null default now()
);

create index if not exists airpool_events_created_idx on public.airpool_events(created_at desc);
create index if not exists airpool_fare_checks_created_idx on public.airpool_fare_checks(created_at desc);

